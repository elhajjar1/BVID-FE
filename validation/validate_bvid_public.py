"""BVID-FE validation harness.

Runs each case in a published (or synthetic) dataset through the selected
BVID-FE tier and reports Mean Absolute Percentage Error (MAE%) on residual
strength. Used both interactively (prints a table) and as a CI gate.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional

import pandas as pd

from bvidfe.analysis import AnalysisConfig, BvidAnalysis
from bvidfe.core.geometry import ImpactorGeometry, PanelGeometry
from bvidfe.impact.mapping import ImpactEvent

DATASET_DIR = Path(__file__).parent / "datasets"

# Per-tier slack on the dataset's target_mae_pct. ``empirical`` and
# ``semi_analytical`` are calibrated closed-form models; ``fe3d`` is the
# stress-field tool and is qualitative: its strength is the first-ply
# failure of a softened damage zone whose stiffness is fitted in-sample to
# three coupons (NCAMP about 21% low), with a fixed FPF averaging length and
# no cohesive surfaces — see the README's Limitations. The looser fe3d gate
# keeps CI from flapping on regressions that are still inside that
# documented model uncertainty.
_TIER_GATE_MULTIPLIER = {
    "empirical": 1.25,
    "semi_analytical": 1.25,
    "fe3d": 2.0,
}


@dataclass
class DatasetCase:
    """A single BVID test record suitable for validation."""

    material: str
    layup_deg: List[float]
    ply_thickness_mm: float
    panel_Lx_mm: float
    panel_Ly_mm: float
    impactor_diameter_mm: float
    impactor_mass_kg: float
    impact_energy_J: float
    loading: str  # "compression" or "tension"
    measured_strength_MPa: float
    boundary: str = "simply_supported"  # PanelGeometry.boundary
    impactor_shape: str = "hemispherical"  # ImpactorGeometry.shape
    measured_dent_mm: Optional[float] = None
    measured_dpa_mm2: Optional[float] = None
    # Undamaged strength measured on the same coupon geometry. When given,
    # the case is scored on predicted knockdown x this strength, which
    # leaves out the pristine-strength model: use it where the fixture caps
    # the undamaged coupon well below the laminate's unnotched strength.
    measured_pristine_MPa: Optional[float] = None
    # Measured unnotched strength of the same material and layup family from
    # a separate source (e.g. NCAMP qualification), for a dataset that
    # reports no undamaged coupon. Reported only: it gives the knockdown and
    # pristine-strength errors (see knockdown_summary), not the score.
    measured_unnotched_MPa: Optional[float] = None
    # Layup group the knockdown summary is broken down by ("" = none).
    layup_label: str = ""
    # Impact panel when the coupon was impacted on a different window than
    # it is tested on (AnalysisConfig.impact_panel); None = the test panel.
    impact_panel_Lx_mm: Optional[float] = None
    impact_panel_Ly_mm: Optional[float] = None
    impact_boundary: Optional[str] = None
    note: str = ""


def case_from_dict(d: dict) -> DatasetCase:
    # Impactor diameter and mass are often missing from papers. A silent
    # default (16 mm, 5.5 kg) would hide that, so a case must state them.
    missing = [k for k in ("impactor_diameter_mm", "impactor_mass_kg") if k not in d]
    if missing:
        raise ValueError(f"dataset case is missing {', '.join(missing)}: {d.get('note', '')!r}")
    return DatasetCase(
        material=d["material"],
        layup_deg=list(d["layup_deg"]),
        ply_thickness_mm=float(d["ply_thickness_mm"]),
        panel_Lx_mm=float(d["panel_Lx_mm"]),
        panel_Ly_mm=float(d["panel_Ly_mm"]),
        impactor_diameter_mm=float(d["impactor_diameter_mm"]),
        impactor_mass_kg=float(d["impactor_mass_kg"]),
        impact_energy_J=float(d["impact_energy_J"]),
        loading=d.get("loading", "compression"),
        measured_strength_MPa=float(d["measured_strength_MPa"]),
        boundary=d.get("boundary", "simply_supported"),
        impactor_shape=d.get("impactor_shape", "hemispherical"),
        measured_dent_mm=d.get("measured_dent_mm"),
        measured_dpa_mm2=d.get("measured_dpa_mm2"),
        measured_pristine_MPa=d.get("measured_pristine_MPa"),
        measured_unnotched_MPa=d.get("measured_unnotched_MPa"),
        layup_label=d.get("layup_label", ""),
        impact_panel_Lx_mm=d.get("impact_panel_Lx_mm"),
        impact_panel_Ly_mm=d.get("impact_panel_Ly_mm"),
        impact_boundary=d.get("impact_boundary"),
        note=d.get("note", ""),
    )


# A dataset's "kind": "measured" (test data from a cited source) or
# "synthetic" (generated by the model itself). Only measured data can score
# a tier other than the one that generated it: --measured selects it.
DATASET_KINDS = ("measured", "synthetic")


def load_dataset(path: Path) -> tuple[str, List[DatasetCase], dict]:
    """Load a dataset JSON. Returns (name, cases, meta-dict)."""
    obj = json.loads(path.read_text())
    name = obj.get("name", path.stem)
    kind = obj.get("kind")
    if kind not in DATASET_KINDS:
        found = "is missing" if kind is None else f"is {kind!r}"
        raise ValueError(
            f'{path.name}: top-level "kind" {found}; set it to '
            f"{' or '.join(repr(k) for k in DATASET_KINDS)}"
        )
    target_mae = float(obj.get("target_mae_pct", 100.0))
    cases = [case_from_dict(c) for c in obj["cases"]]
    # "gate": false marks a dataset the model is known to miss: its error is
    # reported but does not fail --gate. "gate_note" says why.
    return (
        name,
        cases,
        {
            "kind": kind,
            "target_mae_pct": target_mae,
            "gate": bool(obj.get("gate", True)),
            "gate_note": obj.get("gate_note", ""),
        },
    )


def run_case(case: DatasetCase, tier: str) -> dict:
    """Run a single case at the given tier. Returns a row dict."""
    impact_panel = None
    if case.impact_panel_Lx_mm is not None:
        impact_panel = PanelGeometry(
            case.impact_panel_Lx_mm,
            case.impact_panel_Ly_mm,
            boundary=case.impact_boundary or case.boundary,
        )
    cfg = AnalysisConfig(
        material=case.material,
        layup_deg=list(case.layup_deg),
        ply_thickness_mm=case.ply_thickness_mm,
        panel=PanelGeometry(case.panel_Lx_mm, case.panel_Ly_mm, boundary=case.boundary),
        loading=case.loading,
        tier=tier,
        impact=ImpactEvent(
            energy_J=case.impact_energy_J,
            impactor=ImpactorGeometry(
                diameter_mm=case.impactor_diameter_mm, shape=case.impactor_shape
            ),
            mass_kg=case.impactor_mass_kg,
        ),
        impact_panel=impact_panel,
    )
    result = BvidAnalysis(cfg).run()
    predicted = result.residual_strength_MPa
    if case.measured_pristine_MPa is not None:
        predicted = result.knockdown * case.measured_pristine_MPa
    err_pct = 100.0 * abs(predicted - case.measured_strength_MPa) / case.measured_strength_MPa
    # Reported, not scored: the knockdown and the model's pristine strength
    # against a measured undamaged strength, when the case has one.
    pristine = case.measured_pristine_MPa
    if pristine is None:
        pristine = case.measured_unnotched_MPa
    measured_kd = kd_err = pristine_err = None
    if pristine is not None:
        measured_kd = case.measured_strength_MPa / pristine
        kd_err = 100.0 * (result.knockdown / measured_kd - 1.0)
        pristine_err = 100.0 * (result.pristine_strength_MPa / pristine - 1.0)
    return {
        "material": case.material,
        "energy_J": case.impact_energy_J,
        "loading": case.loading,
        "predicted_MPa": predicted,
        "measured_MPa": case.measured_strength_MPa,
        "error_pct": err_pct,
        "predicted_knockdown": result.knockdown,
        "predicted_dpa_mm2": result.dpa_mm2,
        "predicted_dent_mm": result.damage.dent_depth_mm,
        "measured_dent_mm": case.measured_dent_mm,
        "layup": case.layup_label,
        "predicted_pristine_MPa": result.pristine_strength_MPa,
        "measured_pristine_MPa": pristine,
        "measured_knockdown": measured_kd,
        "knockdown_error_pct": kd_err,
        "pristine_error_pct": pristine_err,
        "note": case.note,
    }


def run_dataset(cases: List[DatasetCase], tier: str) -> pd.DataFrame:
    return pd.DataFrame([run_case(c, tier) for c in cases])


def dent_summary(df: pd.DataFrame) -> Optional[dict]:
    """Predicted / measured dent depth over the cases with a positive measured
    dent: ``{"n", "n_nonpositive", "median", "p10", "p90"}``, or None when the
    dataset records no dent. Reported only; the dent is not gated."""
    if "measured_dent_mm" not in df or df["measured_dent_mm"].isna().all():
        return None
    measured = pd.to_numeric(df["measured_dent_mm"], errors="coerce")
    pos = measured > 0
    ratio = df.loc[pos, "predicted_dent_mm"] / measured[pos]
    return {
        "n": int(pos.sum()),
        "n_nonpositive": int((measured <= 0).sum()),
        "median": float(ratio.median()) if len(ratio) else float("nan"),
        "p10": float(ratio.quantile(0.1)) if len(ratio) else float("nan"),
        "p90": float(ratio.quantile(0.9)) if len(ratio) else float("nan"),
    }


def _error_stats(df: pd.DataFrame) -> dict:
    """Strength, knockdown and pristine errors of a set of rows (see
    knockdown_summary). The knockdown and pristine entries are None when no
    row has a measured pristine strength."""
    signed = 100.0 * (df["predicted_MPa"] / df["measured_MPa"] - 1.0)
    out: dict = {
        "n": int(len(df)),
        "strength_mae_pct": float(df["error_pct"].mean()),
        "strength_bias_pct": float(signed.mean()),
    }
    has = df["measured_pristine_MPa"].notna()
    out["n_pristine"] = int(has.sum())
    for key, col in (("knockdown", "knockdown_error_pct"), ("pristine", "pristine_error_pct")):
        err = pd.to_numeric(df.loc[has, col])
        out[f"{key}_mae_pct"] = float(err.abs().mean()) if has.any() else None
        out[f"{key}_bias_pct"] = float(err.mean()) if has.any() else None
    return out


def knockdown_summary(df: pd.DataFrame) -> dict:
    """The gated strength error next to the knockdown error against the
    measured pristine strength. Reported only; the gate is on ``error_pct``.

    Per case with a measured pristine strength P (``measured_pristine_MPa``,
    else ``measured_unnotched_MPa``):

    - knockdown error = predicted knockdown / (measured residual / P) - 1;
    - pristine error = model pristine strength / P - 1.

    Returns ``{"n", "strength_mae_pct", "strength_bias_pct", "n_pristine",
    "knockdown_mae_pct", "knockdown_bias_pct", "pristine_mae_pct",
    "pristine_bias_pct", "by_layup"}`` (percent; MAE is the mean absolute,
    bias the mean signed error; the knockdown and pristine entries are over
    the ``n_pristine`` cases and None when there are none). ``by_layup`` maps
    each ``layup`` label to the same entries for its cases, and is empty
    when no case has a label. A case scored on ``measured_pristine_MPa`` has
    a knockdown error equal to its signed strength error."""
    out = _error_stats(df)
    labels = df["layup"].fillna("") if "layup" in df else pd.Series([""] * len(df))
    out["by_layup"] = {
        str(label): _error_stats(df[labels == label])
        for label in dict.fromkeys(labels)
        if label != ""
    }
    return out


def _format_errors(stats: dict) -> str:
    def pair(key: str) -> str:
        if stats[f"{key}_mae_pct"] is None:
            return "n/a"
        return f"MAE {stats[f'{key}_mae_pct']:.2f}% bias {stats[f'{key}_bias_pct']:+.2f}%"

    return (
        f"strength MAE {stats['strength_mae_pct']:.2f}% bias "
        f"{stats['strength_bias_pct']:+.2f}% | knockdown vs measured pristine "
        f"{pair('knockdown')} | pristine {pair('pristine')}"
    )


def _discover_datasets() -> List[Path]:
    if not DATASET_DIR.exists():
        return []
    return sorted(DATASET_DIR.glob("*.json"))


def _select_datasets(names: Optional[List[str]], kind: Optional[str] = None) -> List[Path]:
    """Datasets by stem name (all of them when ``names`` is None), keeping
    only those whose ``kind`` matches when it is given."""
    paths = _discover_datasets()
    if names is not None:
        paths = [p for p in paths if p.stem in names]
    if kind is not None:
        paths = [p for p in paths if load_dataset(p)[2]["kind"] == kind]
    return paths


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Run BVID-FE validation against digitized datasets."
    )
    parser.add_argument(
        "--tier",
        default="empirical",
        choices=["empirical", "semi_analytical", "fe3d"],
    )
    which = parser.add_mutually_exclusive_group()
    which.add_argument(
        "--dataset",
        nargs="+",
        default=None,
        help="Dataset stem name(s) (without .json). If omitted, run all.",
    )
    which.add_argument(
        "--measured",
        action="store_true",
        help='Run every dataset with "kind": "measured" (leaves out the '
        "synthetic ones, which are generated by the empirical tier).",
    )
    parser.add_argument(
        "--gate",
        action="store_true",
        help="Exit non-zero if MAE exceeds the tier-specific multiplier "
        "of the dataset target_mae_pct (1.25 for empirical / "
        "semi_analytical, 2.0 for fe3d).",
    )
    parser.add_argument(
        "--max-cases",
        type=int,
        default=None,
        help="If set, run only the first N cases of each dataset. Useful for "
        "the fe3d CI step, where each case takes about 30 s (16-ply) to 40 s "
        "(24-ply) on a CI runner.",
    )
    args = parser.parse_args(argv)

    # Every selected file is loaded (and checked) before any case runs, so a
    # malformed dataset fails at once rather than after the others have run.
    try:
        paths = _select_datasets(args.dataset, kind="measured" if args.measured else None)
        datasets = [load_dataset(p) for p in paths]
    except ValueError as exc:
        print(f"Invalid dataset: {exc}", file=sys.stderr)
        return 1
    unknown = sorted(set(args.dataset or []) - {p.stem for p in paths})
    if unknown:
        print(f"Unknown dataset(s): {', '.join(unknown)}", file=sys.stderr)
        return 1
    if not paths:
        print("No datasets found.", file=sys.stderr)
        return 1

    any_gate_fail = False
    multiplier = _TIER_GATE_MULTIPLIER.get(args.tier, 1.25)
    for name, cases, meta in datasets:
        if args.max_cases is not None:
            cases = cases[: args.max_cases]
        df = run_dataset(cases, tier=args.tier)
        mae = float(df["error_pct"].mean())
        max_err = float(df["error_pct"].max())
        target = meta["target_mae_pct"]
        print(f"\n=== {name} ({args.tier}) — {len(cases)} cases ===")
        print(df.to_string(index=False))
        print(
            f"MAE = {mae:.2f}%   max error = {max_err:.2f}%   "
            f"target = {target:.1f}%   gate-multiplier = {multiplier:g}"
        )
        dent = dent_summary(df)
        if dent is not None:
            print(
                f"dent (reported, not gated): median predicted / measured = "
                f"{dent['median']:.2f} (10-90%: {dent['p10']:.2f}-{dent['p90']:.2f}) "
                f"over {dent['n']} cases with a positive measured dent"
                + (f"; {dent['n_nonpositive']} measured <= 0" if dent["n_nonpositive"] else "")
            )
        kd = knockdown_summary(df)
        print(
            f"knockdown (reported, not gated): {_format_errors(kd)} "
            f"({kd['n_pristine']} of {kd['n']} cases with a measured pristine)"
        )
        if len(kd["by_layup"]) > 1:
            for label, stats in kd["by_layup"].items():
                print(f"  layup {label} ({stats['n']} cases): {_format_errors(stats)}")
        if not meta["gate"]:
            print(f"ADVISORY: {name} is not gated. {meta['gate_note']}".rstrip())
        elif args.gate and mae > multiplier * target:
            print(
                f"FAIL: {name} ({args.tier}) MAE {mae:.2f}% exceeds "
                f"{multiplier:g} * {target:.1f}% target",
                file=sys.stderr,
            )
            any_gate_fail = True

    return 1 if any_gate_fail else 0


if __name__ == "__main__":
    sys.exit(main())
